let mapElement;
let locationsData;

export const displayMap = (mapEl) => {
  if (!mapEl) return;

  mapElement = mapEl;
  locationsData = JSON.parse(mapEl.dataset.locations);

  const waitForMaps = setInterval(() => {
    if (typeof google !== 'undefined' && google.maps) {
      clearInterval(waitForMaps);
      initMap();
    }
  }, 100);
};

